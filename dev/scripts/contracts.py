#!/usr/bin/env python3
"""Generate the checked-in contract and TypeScript route map; --check detects drift."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "plugin"))
from webgui.schema import specification


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(typescript({"type": item}) for item in kind)
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"integer", "number"}:
        return "number"
    if kind == "array":
        return "Array<" + typescript(schema.get("items", {})) + ">"
    if kind == "object":
        if "properties" not in schema:
            return "Record<string, " + typescript(schema.get("additionalProperties", {})) + ">"
        required = schema.get("required", [])
        return "{ " + "; ".join(json.dumps(key) + ("" if key in required else "?") + ": " + typescript(value)
                                  for key, value in schema["properties"].items()) + " }"
    return "unknown"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = specification()
    routes = []
    for path, verbs in spec["paths"].items():
        for verb, operation in verbs.items():
            schema = operation["responses"]["200"].get("content", {}).get("application/json", {}).get("schema", {})
            data = schema.get("allOf", [{}, {}])[-1].get("properties", {}).get("data", {})
            routes.append(f'  "{verb.upper()} {path}": Envelope<{typescript(data)}>;')
    types = "// Generated by dev/scripts/contracts.py; do not edit.\nexport interface Routes {\n" + "\n".join(routes) + "\n}\n"
    types += "export type ApiRoute = keyof Routes;\nexport interface Envelope<T> { ok: true; data: T; revision: number; instance: string; cursor: string }\n"
    for name, schema in spec["components"]["schemas"].items():
        if name != "Envelope":
            types += "export type " + name + " = " + typescript(schema) + ";\n"
    outputs = {ROOT / "openapi.yaml": json.dumps(spec, indent=2) + "\n", ROOT / "web/src/api/types.gen.ts": types}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Contract drift: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
